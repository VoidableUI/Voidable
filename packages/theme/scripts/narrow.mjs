// The narrow-screen rules (#119): written once, generated for every breakpoint.
//
// Media queries cannot read custom properties, so a switch an application can move has to
// exist once per position. src/narrow-src/<group>.css holds each rule set once, in a media
// query at the default width (`max-width: 48rem` for the narrow layout, `min-width: 48.0625rem`
// for the wide one). This writes src/narrow/<group>.css: the same rules once per value of
// `data-void-narrow` on <html> (sm 36rem, md 48rem, lg 64rem, off), each selector behind a
// :where() so specificity is what it was. The md set also applies where the attribute is absent
// or not one of the others, so the default is the layout the theme always had. `off` keeps the
// wide layout at every width: narrow rules do not apply, wide rules always do.
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

export const GROUPS = ['shell', 'data', 'page', 'media'];

const ATTR = 'data-void-narrow';
const SIZES = { sm: 36, md: 48, lg: 64 };
const gate = (size) =>
  size === 'md' ? `:root:not([${ATTR}="sm"], [${ATTR}="lg"], [${ATTR}="off"])` : `:root[${ATTR}="${size}"]`;

const isKeyframes = (rule) => rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name);

function variant(atrule, size, kind) {
  const gateSel = size === 'off' ? gate('off') : gate(size);
  const copy = atrule.clone();
  copy.walkRules((rule) => {
    if (isKeyframes(rule)) return;
    rule.selectors = rule.selectors.map((s) => `:where(${gateSel}) ${s}`);
  });
  // Wide rules always apply with `off`; narrow rules never do.
  if (size === 'off') return kind === 'min' ? copy.nodes : [];
  const width = kind === 'max' ? SIZES[size] : SIZES[size] + 1 / 16;
  copy.params = `(${kind}-width: ${width}rem)`;
  return [copy];
}

export function expand(cssText, file) {
  const root = postcss.parse(cssText, { from: file });
  const out = postcss.root();
  root.each((node) => {
    if (node.type === 'comment') return;
    const ok = node.type === 'atrule' && node.name === 'media' && ['(max-width: 48rem)', '(min-width: 48.0625rem)'].includes(node.params);
    if (!ok) throw new Error(`${file}: only @media (max-width: 48rem) and (min-width: 48.0625rem) belong in a narrow template, found ${node.toString().slice(0, 60)}`);
    const kind = node.params.startsWith('(max') ? 'max' : 'min';
    for (const size of ['sm', 'md', 'lg', 'off']) for (const n of variant(node, size, kind)) { const c = n.clone(); c.raws.before = '\n\n'; out.append(c); };
  });
  return out.toString();
}

export const NOTE = '/* Generated by @voidable/theme (scripts/narrow.mjs) from src/narrow-src. Do not edit. */\n';

export function writeNarrow(SRC) {
  for (const g of GROUPS) {
    const to = path.join(SRC, 'narrow', `${g}.css`);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.writeFileSync(to, NOTE + expand(fs.readFileSync(path.join(SRC, 'narrow-src', `${g}.css`), 'utf8'), `narrow-src/${g}.css`));
  }
}
