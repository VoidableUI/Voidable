// Writes one MDX page per component into src/content/docs/components/ and
// returns the sidebar for them. Run from astro.config.mjs, so the files exist
// before Starlight scans the content directory and cannot go stale: they are
// gitignored, and every run rewrites them from the manifest.
//
// A page is a stub of headings and component calls. The tables, examples and
// notes are rendered by src/components/api/*.astro from component-data.mjs, so
// nothing about a component is typed here. Hand-written extras (the Table
// page's responsive behaviour, the Button page's variants) live in
// src/content/docs/components/_<slug>.mdx (the underscore keeps Starlight from
// treating them as pages) and are inlined after the example.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, componentGroups, loadComponentData } from './component-data.mjs';

const DIR = join(ROOT, 'docs/src/content/docs/components');

const yaml = (s) => JSON.stringify(s);

/** Escape what MDX would read as JSX or an expression, outside code spans. */
const mdxSafe = (text) =>
  text
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/\{/g, '\\{').replace(/</g, '&lt;')))
    .join('');

function stub(c) {
  const extraPath = join(DIR, `_${c.slug}.mdx`);
  const extraRaw = existsSync(extraPath) ? readFileSync(extraPath, 'utf8') : '';
  const extra = extraRaw.replace(/^---[\s\S]*?---\n/, '').trim();
  // A hand-written page may carry a better description than the manifest's summary.
  const extraDescription = /^---[\s\S]*?^description:\s*(.+)$[\s\S]*?^---/m.exec(extraRaw)?.[1];
  const sections = [];
  const heading = (title, body) => sections.push(`## ${title}\n\n${body}`);
  const t = c.tag;

  heading('Attributes', `<Attributes tag="${t}" />`);
  if (c.events.length) heading('Events', `<Events tag="${t}" />`);
  heading('Children and placement', `<Placement tag="${t}" />`);
  if (c.form) heading('Form behaviour', `<FormBehaviour tag="${t}" />`);
  if (c.keyboard) heading('Keyboard', `<KeyTable tag="${t}" />`);
  heading('Accessibility', `<Accessibility tag="${t}" />`);
  heading('Common mistakes', `<Mistakes tag="${t}" />`);
  heading('Related', `<Related tag="${t}" />`);

  const lead = [c.description, ...c.details].join('\n\n');
  return `---
title: ${yaml(c.title)}
description: ${yaml(extraDescription ?? c.summary)}
sidebar:
  label: ${yaml(c.title)}
editUrl: false
---
import Live from '../../../components/api/Live.astro';
import Attributes from '../../../components/api/Attributes.astro';
import Events from '../../../components/api/Events.astro';
import Placement from '../../../components/api/Placement.astro';
import FormBehaviour from '../../../components/api/FormBehaviour.astro';
import KeyTable from '../../../components/api/KeyTable.astro';
import Accessibility from '../../../components/api/Accessibility.astro';
import Mistakes from '../../../components/api/Mistakes.astro';
import Related from '../../../components/api/Related.astro';

{/* Generated by src/lib/component-pages.mjs from the Custom Elements Manifest. Do not edit: change the component's JSDoc, its snippet in tools/voidable, or docs/src/data/. */}

${mdxSafe(lead)}

<Live tag="${t}" />
${extra ? `\n${extra}\n` : ''}
${sections.join('\n\n')}
`;
}

export function writeComponentPages() {
  const { components } = loadComponentData();
  mkdirSync(DIR, { recursive: true });
  const keep = new Set(components.map((c) => `${c.slug}.mdx`));
  for (const f of readdirSync(DIR)) {
    // Generated pages only: hand-written files (overview, keyboard, _extras) stay.
    if (!f.endsWith('.mdx') || f.startsWith('_') || keep.has(f)) continue;
    if (['overview.mdx', 'keyboard.mdx', 'overlays.mdx'].includes(f)) continue;
    rmSync(join(DIR, f));
  }
  for (const c of components) {
    const body = stub(c);
    const path = join(DIR, `${c.slug}.mdx`);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== body) writeFileSync(path, body);
  }
}

/** Sidebar items for the Components section: overview, keyboard, then one group per category. */
export function componentSidebar() {
  return [
    { label: 'Overview', slug: 'components/overview' },
    { label: 'Keyboard and ARIA', slug: 'components/keyboard' },
    { label: 'Overlays', slug: 'components/overlays' },
    ...componentGroups().map((g) => ({
      label: g.label,
      collapsed: true,
      items: g.components.map((c) => ({ label: c.title, slug: `components/${c.slug}` })),
    })),
    { label: 'Storybook', link: '/storybook/', attrs: { target: '_blank' } },
  ];
}
